"""笠雲の候補を機械的に絞り込む。**判定はしない。** 人が見る枚数を減らすだけ。

同日にAIの目視判定を2回外している（2026-09-15）。自動でラベルは付けない。

富士市ライブカメラは固定。2022〜2026年の111枚の中央値画像で稜線が鮮明に出ることで
確認済み。よって山頂の画素位置は定数でよい。稜線の自動検出は霞と空のグラデーションで
誤検出を繰り返したため採用しない。
"""
import numpy as np
from PIL import Image

SUMMIT = (330, 292)               # 快晴枠 2026-09-14 07時 と 2023-12-24 16時 で目視確認

# **笠雲は山頂に乗って横へ広がる。** 最初 y230-290 / x290-370 という
# 「山頂の上の空」を見ていたため、確定陽性 2023-12-24 16時（山頂に乗った
# きれいなレンズ雲）で枠の中身がほぼ空になり、明るさ差 +2.9 しか出なかった
# （2026-09-15、画像を実際に見て判明）。
ON = (slice(262, 302), slice(265, 395))       # 山頂被覆型：山頂に乗る笠
ABOVE = (slice(200, 262), slice(250, 410))    # 離れ笠：山頂の上に浮く笠
BAND = slice(190, 300)                        # 同じ高さの空
SKY_L, SKY_R = slice(60, 200), slice(460, 600)
# 可視判定は**山腹の下のほう**で測る。山頂で測ってはいけない——
# 笠雲は山頂を明るくするので、山頂で測ると笠雲そのものを
# 「山が見えない」と誤判定して弾く（2026-09-15 に実際にそうなった）。
BODY = (slice(320, 355), slice(200, 270))     # 左の山腹
BODY2 = (slice(320, 355), slice(400, 470))    # 右の山腹


def features(path):
    rgb = np.asarray(Image.open(path).convert("RGB"), dtype=float)
    g = rgb.mean(axis=2)
    on, above = g[ON], g[ABOVE]
    sky = np.concatenate([g[BAND, SKY_L].ravel(), g[BAND, SKY_R].ravel()])
    body = np.concatenate([g[BODY].ravel(), g[BODY2].ravel()])
    return {
        "contrast": float(max(on.mean(), above.mean()) - sky.mean()),
        "contrast_on": float(on.mean() - sky.mean()),
        # **明るさの符号では拾えない。** 逆光の笠雲は空より暗く写る
        # （2026-09-05 09時は -24.2）。見るのは「周りの空は平坦なのに
        # 山頂の上だけ構造があるか」。明暗どちらの雲でも効く
        "texture": float(max(on.std(), above.std()) / max(sky.std(), 1.0)),
        "above_std": float(max(on.std(), above.std())),
        "sky_mean": float(sky.mean()),
        "sky_std": float(sky.std()),
        # 山腹が空より暗く見えていれば山が見えている。
        # 全面曇天では差が消える
        "visible": float(sky.mean() - body.mean()),
        # **周りが晴れているか。** 青空は青が赤より強く、曇り空は灰色（青≒赤）。
        # グレースケールに落とすとこの差が消える。最初それをやって、
        # 無作為日の誤検出5区間が全部「全体的に曇り」になった
        # （2026-09-15 ユーザー指摘）
        "blue": float((np.concatenate([rgb[BAND, SKY_L].reshape(-1, 3),
                                       rgb[BAND, SKY_R].reshape(-1, 3)])[:, 2]
                       - np.concatenate([rgb[BAND, SKY_L].reshape(-1, 3),
                                         rgb[BAND, SKY_R].reshape(-1, 3)])[:, 0]).mean()),
    }


def usable(f, *, min_sky=45):
    """夜間と、一帯が雲の枠を外す。**判定はこれだけ。**

    **青−赤（空の青さ）は使わない。** 2026-09-16 に外した。雲の高さを区別できず、
    山頂より高い雲でも値が下がる。朝夕の色味でも動く。実際に笠雲を落とした例が5件:

        2022-03-01 07時 +4.3 / 09時 -1.8 / 2024-01-23 07時 +8.9
        2025-12-11 16時 +9.1 / 2022-09-23 11時 -2.6（惜しい）

    5件とも輪郭は17以上。**低い雲が山を隠せば輪郭が消える**ので、
    「その地点から見えるか」は輪郭のほうが正しく測れる。

    **可視判定（山が見えているか）は持たない。** 2026-09-16 に確定ラベルで測ると、

        確定陽性9枠   輪郭 3.0〜34.0 / 明暗差 +7.4〜+43.3 / 青−赤 +18.9〜+57.2
        確定曇天5枠   輪郭 3.0〜 8.0 / 明暗差 +9.6〜+73.5 / 青−赤  -3.8〜 +5.7

    輪郭も明暗差も重なるが、青−赤だけ重ならない。周りが青空なら山を隠すものが無い。

    以前は「空より山腹が暗ければ見えている」としていたが、**日が高いと山肌が
    直射日光で空より明るくなり、よく見えている枠ほど除外していた**（青空の
    4,464枠のうち2,486枠、日中9〜13時は8割）。現象がよく見えている状態を
    見えていない証拠に使う誤りは、この日3回目（surround項、山頂での可視判定、これ）。
    """
    return f["sky_mean"] >= min_sky and f["edge"] >= 12.0


def candidates(frames, *, tex=1.3, con=3.0, min_run=1):
    """1日ぶんの枠（時刻順）から候補を返す。

    `min_run` は既定で1。**連続性をゲートにしない。** 確定陽性の
    2023-12-24 16時は前後の枠が条件を満たさない単発で、min_run=2 だと落ちる。
    報道にも「約1時間で消滅」（2023-12-20）とあり、毎時1枚では定常性を担保できない。
    """
    # 山頂の異常は**明るさ差か粗さ比のどちらか**。確定陽性2件は片方ずつしか
    # 満たさない（2026-01-05 09時=粗さ比2.38・差+26.1／2023-12-24 16時=粗さ比0.62・差+3.4）。
    # 誤検出を切るのは `usable` の青空条件が担う
    ok = [f is not None and usable(f)
          and (f["texture"] >= tex or f["contrast"] >= con) for f in frames]
    out, i = [], 0
    while i < len(ok):
        if not ok[i]:
            i += 1
            continue
        j = i
        while j < len(ok) and ok[j]:
            j += 1
        if j - i >= min_run:
            out.append((i, j))          # [i, j) の連続区間
        i = j
    return out
